CREATE TABLE departments (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name VARCHAR(120) NOT NULL UNIQUE);
CREATE TABLE roles (name VARCHAR(32) PRIMARY KEY);
INSERT INTO roles(name) VALUES ('SUPER_ADMIN'), ('ADMIN'), ('ENGINEER');
CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 employee_code VARCHAR(40) NOT NULL UNIQUE,
 full_name VARCHAR(160) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 phone VARCHAR(40),
 department_id BIGINT REFERENCES departments(id),
 position VARCHAR(120),
 active BOOLEAN NOT NULL DEFAULT TRUE,
 failed_attempts INTEGER NOT NULL DEFAULT 0 CHECK (failed_attempts >= 0),
 locked_until TIMESTAMPTZ, last_login TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE user_roles (user_id BIGINT NOT NULL REFERENCES users(id),role_name VARCHAR(32) NOT NULL REFERENCES roles(name),PRIMARY KEY(user_id,role_name));
CREATE TABLE audit_logs (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,actor_id BIGINT REFERENCES users(id),action VARCHAR(80) NOT NULL,created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE INDEX audit_logs_created_idx ON audit_logs(created_at);
CREATE TABLE system_settings (key VARCHAR(100) PRIMARY KEY,value VARCHAR(500) NOT NULL,updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP);