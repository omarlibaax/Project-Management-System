CREATE SEQUENCE project_code_seq START WITH 1;
ALTER TABLE users ADD COLUMN version BIGINT NOT NULL DEFAULT 0;
CREATE UNIQUE INDEX users_email_case_insensitive_idx ON users(lower(email));
CREATE TABLE projects (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(40) NOT NULL UNIQUE,
 name VARCHAR(180) NOT NULL,
 description VARCHAR(4000) NOT NULL DEFAULT '',
 category VARCHAR(120) NOT NULL,
 location VARCHAR(240) NOT NULL,
 client VARCHAR(180) NOT NULL,
 manager_id BIGINT NOT NULL REFERENCES users(id),
 planned_start_date DATE NOT NULL,
 planned_end_date DATE NOT NULL,
 original_start_date DATE NOT NULL,
 original_end_date DATE NOT NULL,
 actual_start_date DATE,
 actual_end_date DATE,
 revised_end_date DATE,
 priority VARCHAR(20) NOT NULL CHECK(priority IN ('LOW','MEDIUM','HIGH')),
 status VARCHAR(32) NOT NULL CHECK(status IN ('PLANNED','IN_PROGRESS','ON_HOLD','PENDING_APPROVAL','COMPLETED','CANCELLED')),
 planned_budget NUMERIC(19,2) NOT NULL DEFAULT 0 CHECK(planned_budget >= 0),
 approved_budget NUMERIC(19,2) NOT NULL DEFAULT 0 CHECK(approved_budget >= 0),
 actual_expenditure NUMERIC(19,2) NOT NULL DEFAULT 0 CHECK(actual_expenditure >= 0),
 progress NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK(progress BETWEEN 0 AND 100),
 archived BOOLEAN NOT NULL DEFAULT FALSE,
 created_by BIGINT NOT NULL REFERENCES users(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 version BIGINT NOT NULL DEFAULT 0,
 CHECK(planned_end_date >= planned_start_date),
 CHECK(original_end_date >= original_start_date),
 CHECK(actual_end_date IS NULL OR (actual_start_date IS NOT NULL AND actual_end_date >= actual_start_date)),
 CHECK(revised_end_date IS NULL OR revised_end_date >= planned_start_date)
);
CREATE INDEX projects_status_priority_idx ON projects(status,priority) WHERE NOT archived;
CREATE INDEX projects_deadline_idx ON projects(planned_end_date) WHERE NOT archived;
CREATE INDEX projects_manager_idx ON projects(manager_id);
CREATE TABLE project_schedule_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES projects(id),
 previous_start DATE NOT NULL,
 previous_end DATE NOT NULL,
 new_start DATE NOT NULL,
 new_end DATE NOT NULL,
 reason VARCHAR(1000) NOT NULL,
 changed_by BIGINT NOT NULL REFERENCES users(id),
 changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(new_end >= new_start)
);
CREATE INDEX project_schedule_history_project_idx ON project_schedule_history(project_id,changed_at);
