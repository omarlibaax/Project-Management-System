CREATE TABLE project_assignments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES projects(id),
 engineer_id BIGINT NOT NULL REFERENCES users(id),
 assigned_by BIGINT NOT NULL REFERENCES users(id),
 assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 revoked_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX active_project_assignment ON project_assignments(project_id,engineer_id) WHERE revoked_at IS NULL;
CREATE INDEX assignments_engineer ON project_assignments(engineer_id,project_id) WHERE revoked_at IS NULL;
CREATE TABLE project_tasks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES projects(id),
 title VARCHAR(240) NOT NULL,
 engineer_id BIGINT NOT NULL REFERENCES users(id),
 due_date DATE NOT NULL,
 weight NUMERIC(9,2) NOT NULL CHECK(weight > 0),
 progress NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK(progress BETWEEN 0 AND 100),
 version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX tasks_project ON project_tasks(project_id);
CREATE TABLE project_resources (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES projects(id),
 kind VARCHAR(20) NOT NULL CHECK(kind IN ('LABOR','MATERIAL')),
 name VARCHAR(240) NOT NULL,
 unit VARCHAR(40) NOT NULL,
 planned NUMERIC(14,2) NOT NULL CHECK(planned >= 0),
 used NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK(used >= 0),
 unit_cost NUMERIC(19,2) NOT NULL CHECK(unit_cost >= 0),
 version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE project_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES projects(id),
 kind VARCHAR(20) NOT NULL CHECK(kind IN ('PROGRESS','EXPENSE','BUDGET','EXTENSION','COMPLETION')),
 task_id BIGINT REFERENCES project_tasks(id),
 amount NUMERIC(19,2),
 requested_date DATE,
 reason VARCHAR(2000) NOT NULL,
 submitted_by BIGINT NOT NULL REFERENCES users(id),
 submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 state VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(state IN ('PENDING','APPROVED','REJECTED')),
 reviewed_by BIGINT REFERENCES users(id),
 reviewed_at TIMESTAMPTZ,
 review_note VARCHAR(2000)
);
CREATE UNIQUE INDEX pending_task_progress ON project_requests(task_id) WHERE state='PENDING' AND kind='PROGRESS';
CREATE UNIQUE INDEX pending_project_completion ON project_requests(project_id) WHERE state='PENDING' AND kind='COMPLETION';
CREATE INDEX requests_project ON project_requests(project_id,submitted_at);
CREATE TABLE project_evidence (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 request_id BIGINT NOT NULL REFERENCES project_requests(id),
 name VARCHAR(240) NOT NULL,
 media_type VARCHAR(80) NOT NULL,
 content BYTEA NOT NULL,
 uploaded_by BIGINT NOT NULL REFERENCES users(id),
 uploaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(octet_length(content) <= 5242880)
);
CREATE TABLE notifications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id),
 project_id BIGINT NOT NULL REFERENCES projects(id),
 message VARCHAR(500) NOT NULL,
 dedup_key VARCHAR(160) UNIQUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 read_at TIMESTAMPTZ
);
CREATE INDEX notifications_user ON notifications(user_id,created_at);
